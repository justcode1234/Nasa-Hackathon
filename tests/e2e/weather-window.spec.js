import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),axe=readFileSync(require.resolve('axe-core/axe.min.js'),'utf8');

test('a crop slot opens its exact strategy rain window and input edits clear that window',async({page,context},info)=>{
  test.setTimeout(180_000);const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await context.route(/overpass-api\.de|overpass\.private\.coffee|maps\.mail\.ru|\/api\/farms\?/,route=>route.abort('failed'));
  await page.goto('/',{waitUntil:'domcontentloaded'});
  await page.getByRole('combobox',{name:'Explore an example farming region',exact:true}).selectOption('-31.89,116.77');
  await expect(page.locator('#catalog-status')).toContainText('Australia:');
  await page.getByRole('spinbutton',{name:'Historical reference year',exact:true}).fill('2025');
  await page.getByRole('button',{name:/Next: NASA evidence/}).click();
  await expect(page.locator('#evidence-status')).toContainText('Historical evidence loaded',{timeout:45_000});
  await page.getByRole('button',{name:/Next: Plan crops/}).click();
  for(const [i,value] of ['tomato','cabbage','onion'].entries())await page.getByRole('combobox',{name:['First crop','Second crop','Third crop'][i],exact:true}).selectOption(value);
  await page.getByRole('button',{name:'Compare baseline and two alternatives',exact:true}).click();
  await expect(page.locator('.scenario')).toHaveCount(3);
  // Capture the actual engine-produced slot at the real user action boundary.
  await page.evaluate(()=>window.addEventListener('fieldshift:weather-window',e=>window.actualWindow=e.detail));
  const slot=page.getByRole('button',{name:'View historical rain in 3D: Existing rotation, slot 2, Cabbage',exact:true});
  await slot.click();
  await expect(page.locator('#map3d-window')).toBeVisible({timeout:60_000});
  await expect(page.locator('#map3d-window')).toContainText('80 mapped days');
  await expect(page.locator('#map3d-window')).toBeFocused();
  await expect(page.locator('#map3d-legend')).toContainText('Existing rotation, slot 2: Cabbage');
  await expect(page.locator('#map3d-values caption')).toContainText('Existing rotation, slot 2: Cabbage');
  const actual=await page.evaluate(()=>({engine:window.actualWindow,view:window.fieldshift3D.snapshot()}));
  expect(actual.view.window.periods).toEqual(['2025-05','2025-06','2025-07']);
  const selected=actual.view.features.find(f=>f.properties.selected).properties;
  expect(selected.value).toBe(actual.engine.slot.indicators.precipitationMm);
  expect(selected.validDays).toBe(actual.engine.slot.indicators.precipitationValidDays);
  expect(selected.expectedDays).toBe(actual.engine.slot.indicators.assessedDays);
  expect(selected.partial).toBe(actual.engine.slot.indicators.precipitationPartial);
  await expect(page.locator('#map3d-month')).toBeDisabled();await expect(page.locator('#map3d-month')).toBeHidden();
  await expect(page.locator('.selected-evidence-month')).toHaveCount(3);
  await page.evaluate(axe);
  const access=await page.evaluate(()=>window.axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa','wcag22aa','best-practice']}}));
  expect(access.violations).toEqual([]);
  await info.attach('Crop-window axe and manual-review items',{body:Buffer.from(JSON.stringify(access,null,2)),contentType:'application/json'});
  await info.attach('Engine slot and rendered native-cell values',{body:Buffer.from(JSON.stringify(actual,null,2)),contentType:'application/json'});
  await page.screenshot({path:info.outputPath('crop-weather-window.png')});
  await page.getByRole('button',{name:'Return to monthly view',exact:true}).click();
  await expect(page.locator('#map3d-window')).toBeHidden();
  await expect(page.getByRole('slider',{name:/Historical month/})).toBeEnabled();
  await page.getByRole('tab',{name:/04.*Compare/}).click();await slot.click();
  await expect(page.locator('#map3d-window')).toBeVisible();
  await page.getByRole('tab',{name:/03.*Plan crops/}).click();
  await page.getByRole('spinbutton',{name:'Planning year',exact:true}).fill('2028');
  expect(await page.evaluate(()=>window.fieldshift3D.snapshot().window)).toBeNull();
  await expect(page.locator('.scenario')).toHaveCount(0);
  expect(errors).toEqual([]);
});
